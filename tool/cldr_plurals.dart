// Regenerates the CLDR plural rule table used by `generate`.
//
// Usage:
//
//   npm pack cldr-core@48.2.0 && tar xzf cldr-core-48.2.0.tgz
//   dart run tool/cldr_plurals.dart package/supplemental
//
// Reads `plurals.json` (cardinal) and `ordinals.json` (ordinal) from the
// given directory and writes:
//
// * `lib/src/generate/cldr/plural_data.dart` — the rule expressions as a
//   Dart const, one map per plural type;
// * `test/fixtures/cldr_plural_samples.json` — the `@integer` / `@decimal`
//   samples of every rule, used by the tests to verify the evaluator.
//
// The output is deterministic: locales and categories are sorted.
import 'dart:convert';
import 'dart:io' as io;

const _categories = ['zero', 'one', 'two', 'few', 'many', 'other'];

void main(List<String> args) {
  if (args.length != 1) {
    io.stderr.writeln('Usage: dart run tool/cldr_plurals.dart <supplemental>');
    io.exit(64);
  }
  final dir = args.single;
  final cardinal = _read('$dir/plurals.json', 'plurals-type-cardinal');
  final ordinal = _read('$dir/ordinals.json', 'plurals-type-ordinal');
  final version = cardinal.version;
  if (version != ordinal.version) {
    io.stderr.writeln('CLDR versions differ: $version vs ${ordinal.version}');
    io.exit(1);
  }
  final package = _packageVersion(dir);

  final out = StringBuffer()
    ..writeln('// GENERATED by tool/cldr_plurals.dart, do not edit by hand.')
    ..writeln('//')
    ..writeln('// Source: Unicode CLDR $version '
        '(npm package cldr-core@$package,')
    ..writeln('// supplemental/plurals.json and supplemental/ordinals.json).')
    ..writeln('// Copyright © 1991-2025 Unicode, Inc. Unicode License v3,')
    ..writeln('// https://www.unicode.org/license.txt')
    ..writeln()
    ..writeln('// ignore_for_file: lines_longer_than_80_chars')
    ..writeln()
    ..writeln('/// Unicode CLDR release the plural rules were taken from.')
    ..writeln("const String cldrVersion = '$package';")
    ..writeln()
    ..writeln(
        '/// CLDR cardinal plural rules: locale -> category -> condition.')
    ..writeln('///')
    ..writeln(
        '/// Locales use `_` as separator. The `other` category is implicit')
    ..writeln('/// (it is the fallback of every locale) and therefore omitted.')
    ..writeln('const Map<String, Map<String, String>> cldrCardinalRules = {');
  _writeTable(out, cardinal.rules);
  out
    ..writeln('};')
    ..writeln()
    ..writeln('/// CLDR ordinal plural rules: locale -> category -> condition.')
    ..writeln('///')
    ..writeln('/// Same layout as [cldrCardinalRules].')
    ..writeln('const Map<String, Map<String, String>> cldrOrdinalRules = {');
  _writeTable(out, ordinal.rules);
  out.writeln('};');

  const dataPath = 'lib/src/generate/cldr/plural_data.dart';
  io.File(dataPath).writeAsStringSync(out.toString());
  io.Process.runSync(io.Platform.resolvedExecutable, ['format', dataPath]);

  final samples = <String, Object?>{
    'cldrVersion': package,
    'cardinal': cardinal.samples,
    'ordinal': ordinal.samples,
  };
  io.File('test/fixtures/cldr_plural_samples.json')
    ..parent.createSync(recursive: true)
    ..writeAsStringSync(
      '${const JsonEncoder.withIndent(' ').convert(samples)}\n',
    );
  io.stdout.writeln(
    'CLDR $package: ${cardinal.rules.length} cardinal, '
    '${ordinal.rules.length} ordinal locales.',
  );
}

typedef _Table = ({
  String version,
  Map<String, Map<String, String>> rules,
  Map<String, Map<String, String>> samples,
});

_Table _read(String path, String key) {
  final json = jsonDecode(io.File(path).readAsStringSync());
  if (json case {'supplemental': final Map<String, Object?> supplemental}) {
    return _readSupplemental(supplemental, path, key);
  }
  throw FormatException('Unexpected layout of $path');
}

_Table _readSupplemental(
  Map<String, Object?> supplemental,
  String path,
  String key,
) {
  final version = switch (supplemental['version']) {
    {'_cldrVersion': final String v} => v,
    _ => 'unknown',
  };
  final table = supplemental[key];
  if (table is! Map<String, Object?>) {
    throw FormatException('No "$key" in $path');
  }
  final rules = <String, Map<String, String>>{};
  final samples = <String, Map<String, String>>{};
  final locales = table.keys.toList()..sort();
  for (final locale in locales) {
    final entry = table[locale];
    if (entry is! Map<String, Object?>) continue;
    final code = locale.replaceAll('-', '_');
    final conditions = <String, String>{};
    final examples = <String, String>{};
    for (final category in _categories) {
      final raw = entry['pluralRule-count-$category'];
      if (raw is! String) continue;
      final at = raw.indexOf('@');
      final condition = (at < 0 ? raw : raw.substring(0, at)).trim();
      final sample = at < 0 ? '' : raw.substring(at).trim();
      if (category != 'other') conditions[category] = condition;
      examples[category] = sample;
    }
    rules[code] = conditions;
    samples[code] = examples;
  }
  return (version: version, rules: rules, samples: samples);
}

String _packageVersion(String supplementalDir) {
  final file = io.File('$supplementalDir/../package.json');
  if (!file.existsSync()) return 'unknown';
  final json = jsonDecode(file.readAsStringSync());
  return switch (json) {
    {'version': final String v} => v,
    _ => 'unknown',
  };
}

void _writeTable(StringBuffer out, Map<String, Map<String, String>> rules) {
  for (final MapEntry(key: locale, value: conditions) in rules.entries) {
    if (conditions.isEmpty) {
      out.writeln("  '$locale': <String, String>{},");
      continue;
    }
    out.writeln("  '$locale': {");
    for (final MapEntry(key: category, value: condition)
        in conditions.entries) {
      out.writeln("    '$category': '$condition',");
    }
    out.writeln('  },');
  }
}
